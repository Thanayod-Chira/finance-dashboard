// "Pool" คือกลุ่มของการเชื่อมต่อฐานข้อมูลที่เปิดทิ้งไว้ล่วงหน้าหลายๆ เส้น
// เวลาโค้ดส่วนไหนอยากคุยกับฐานข้อมูล ก็ "ยืม" เส้นการเชื่อมต่อจาก pool
// ใช้เสร็จก็คืนกลับ ทำให้เร็วกว่าการเปิด-ปิดการเชื่อมต่อใหม่ทุกครั้ง
//
// เราสร้างไฟล์นี้แยกไว้ไฟล์เดียว แล้วให้ทุก route import ไปใช้ร่วมกัน
// (pattern นี้เรียกว่า "singleton" - มีอยู่ตัวเดียวในระบบ)
// ============================================================

const { Pool } = require('pg');
require('dotenv').config();

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // ssl: { rejectUnauthorized: false }  // เปิดบรรทัดนี้ถ้า deploy ขึ้น cloud ที่บังคับ SSL เช่น Render, Railway
});

// ทดสอบว่าต่อฐานข้อมูลได้จริงตอนเริ่มโปรแกรม จะได้เห็น error ทันทีถ้าตั้งค่าผิด
pool.query('SELECT NOW()')
  .then(() => console.log('✅ เชื่อมต่อ PostgreSQL สำเร็จ'))
  .catch((err) => console.error('❌ เชื่อมต่อ PostgreSQL ไม่สำเร็จ:', err.message));

module.exports = pool;
